package com.example.tablestructure.service;

import com.example.tablestructure.model.ColumnInfo;
import com.example.tablestructure.model.ForeignKeyInfo;
import com.example.tablestructure.model.IndexInfo;
import com.example.tablestructure.model.KeyInfo;
import com.example.tablestructure.model.TableInfo;
import com.example.tablestructure.model.TableStructure;
import com.intellij.database.Dbms;
import com.intellij.database.model.DasColumn;
import com.intellij.database.model.DasForeignKey;
import com.intellij.database.model.DasIndex;
import com.intellij.database.model.DasTable;
import com.intellij.database.model.DasTableKey;
import com.intellij.database.model.DasTypedObject;
import com.intellij.database.model.DataType;
import com.intellij.database.types.DasType;
import com.intellij.database.model.MultiRef;
import com.intellij.database.model.NameVersion;
import com.intellij.database.psi.DbDataSource;
import com.intellij.database.psi.DbTable;
import com.intellij.database.util.DasUtil;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;

/**
 * 从 DataGrip 的数据库模型（{@code Das*} API）读取表结构，转换成与 UI 解耦的不可变 DTO。
 *
 * <p>重要：数据库模型是 PSI / 模型对象，必须在读锁内访问。推荐通过
 * {@code ReadAction.nonBlocking(...).inSmartMode(project)} 在后台线程调用本类。</p>
 *
 * <p>本实现不发起任何 JDBC 查询：列、索引、主键/唯一约束、外键都来自
 * DataGrip 已经内省（introspect）好的模型，因此打开速度只取决于模型是否已加载。</p>
 */
public final class TableStructureLoader {

    private TableStructureLoader() {
    }

    /**
     * 读取表结构。必须在读锁（{@link com.intellij.openapi.application.ReadAction}）中调用。
     *
     * @throws IllegalStateException 表对象已失效（被删除 / 数据源刷新 / 模型卸载）
     */
    public static @NotNull TableStructure load(@NotNull DbTable dbTable) {
        DasTable table = dbTable.getDasObject();
        if (table == null) {
            throw new IllegalStateException("表对象不可用（可能已被删除，或数据源模型尚未加载）");
        }

        DbDataSource dataSource = dbTable.getDataSource();
        Dbms dbms = dataSource.getDbms();
        NameVersion databaseVersion = dataSource.getDatabaseVersion();

        List<ColumnInfo> columns = readColumns(table);
        List<IndexInfo> indexes = readIndexes(table);
        List<KeyInfo> keys = readKeys(table);
        List<ForeignKeyInfo> foreignKeys = readForeignKeys(table);

        TableInfo tableInfo = new TableInfo(
                emptyIfNull(DasUtil.getSchema(table)),
                emptyIfNull(table.getName()),
                emptyIfNull(table.getComment()),
                emptyIfNull(dataSource.getName()),
                dbms == null ? "" : emptyIfNull(dbms.getDisplayName()),
                databaseVersion == null ? "" : emptyIfNull(databaseVersion.version),
                table.getKind() == null ? "" : emptyIfNull(table.getKind().getPresentableName()),
                table.isTemporary(),
                table.isSystem(),
                columns.size(),
                indexes.size(),
                keys.size(),
                foreignKeys.size()
        );

        return new TableStructure(tableInfo, columns, indexes, keys, foreignKeys);
    }

    // ------------------------------------------------------------------ columns

    private static @NotNull List<ColumnInfo> readColumns(@NotNull DasTable table) {
        List<ColumnInfo> result = new ArrayList<>();
        for (DasColumn column : DasUtil.getColumns(table)) {
            DasType dasType = column.getDasType();
            DataType dataType = dasType == null ? null : dasType.toDataType();
            String typeDisplay = dataType == null ? "" : emptyIfNull(dataType.getSpecification());
            int length = dataType == null ? 0 : dataType.getLength();
            int precision = dataType == null ? 0 : dataType.getPrecision();
            int scale = dataType == null ? 0 : dataType.getScale();

            result.add(new ColumnInfo(
                    column.getPosition(),
                    emptyIfNull(column.getName()),
                    typeDisplay,
                    length,
                    precision,
                    scale,
                    column.isNotNull(),
                    emptyIfNull(column.getDefault()),
                    DasUtil.isPrimary(column),
                    DasUtil.isForeign(column),
                    DasUtil.isAutoGenerated(column),
                    DasUtil.isComputed(column),
                    emptyIfNull(column.getComment())
            ));
        }
        return result;
    }

    // ------------------------------------------------------------------ indexes

    private static @NotNull List<IndexInfo> readIndexes(@NotNull DasTable table) {
        List<IndexInfo> result = new ArrayList<>();
        for (DasIndex index : DasUtil.getIndices(table)) {
            result.add(new IndexInfo(
                    emptyIfNull(index.getName()),
                    index.isUnique(),
                    index.isFunctionBased(),
                    columnNames(index.getColumnsRef()),
                    emptyIfNull(index.getComment())
            ));
        }
        return result;
    }

    // ------------------------------------------------------------------ keys

    private static @NotNull List<KeyInfo> readKeys(@NotNull DasTable table) {
        List<KeyInfo> result = new ArrayList<>();
        for (DasTableKey key : DasUtil.getTableKeys(table)) {
            result.add(new KeyInfo(
                    emptyIfNull(key.getName()),
                    key.isPrimary(),
                    columnNames(key.getColumnsRef())
            ));
        }
        return result;
    }

    // ------------------------------------------------------------------ foreign keys

    private static @NotNull List<ForeignKeyInfo> readForeignKeys(@NotNull DasTable table) {
        List<ForeignKeyInfo> result = new ArrayList<>();
        for (DasForeignKey foreignKey : DasUtil.getForeignKeys(table)) {
            result.add(new ForeignKeyInfo(
                    emptyIfNull(foreignKey.getName()),
                    columnNames(foreignKey.getColumnsRef()),
                    qualify(foreignKey.getRefTableCatalog(), foreignKey.getRefTableSchema(), foreignKey.getRefTableName()),
                    columnNames(foreignKey.getRefColumns()),
                    foreignKey.getDeleteRule() == null ? "" : foreignKey.getDeleteRule().name(),
                    foreignKey.getUpdateRule() == null ? "" : foreignKey.getUpdateRule().name(),
                    foreignKey.getDeferrability() == null ? "" : foreignKey.getDeferrability().name()
            ));
        }
        return result;
    }

    // ------------------------------------------------------------------ helpers

    private static @NotNull String columnNames(@Nullable MultiRef<? extends DasTypedObject> reference) {
        if (reference == null) {
            return "";
        }
        StringBuilder result = new StringBuilder();
        for (String name : reference.names()) {
            if (result.length() > 0) {
                result.append(", ");
            }
            result.append(name);
        }
        return result.toString();
    }

    private static @NotNull String qualify(@Nullable String catalog, @Nullable String schema, @Nullable String name) {
        StringBuilder result = new StringBuilder();
        if (catalog != null && !catalog.isEmpty()) {
            result.append(catalog).append('.');
        }
        if (schema != null && !schema.isEmpty()) {
            result.append(schema).append('.');
        }
        result.append(emptyIfNull(name));
        return result.toString();
    }

    private static @NotNull String emptyIfNull(@Nullable String value) {
        return value == null ? "" : value;
    }
}
