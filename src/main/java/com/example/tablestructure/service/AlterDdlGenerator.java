package com.example.tablestructure.service;

import com.example.tablestructure.model.ColumnInfo;
import org.jetbrains.annotations.NotNull;

import java.util.List;

/**
 * 由列信息生成 {@code ALTER TABLE ... ADD (...)} 语句，用于「在测试库改结构、把语句拿到正式库执行」。
 *
 * <p>只做字符串拼接，不发起任何数据库访问，因此可以在 EDT 上直接调用，也便于自检。</p>
 *
 * <p>为什么自己拼而不用 DataGrip 的 {@code DdlBuilder}：那个 builder 是「按对象生成整表 DDL」，
 * 而这里要的是「只把选中的几列拼成 ALTER」；自己拼能让语句与用户选中的列一一对应、可控可测。
 * 代价是类型/默认值直接沿用模型里的展示文本（{@link ColumnInfo#typeDisplay()}），
 * 不做方言级的类型归一化。</p>
 */
public final class AlterDdlGenerator {

    private AlterDdlGenerator() {
    }

    /**
     * 生成新增列的 ALTER 语句，每列一条 {@code ALTER TABLE ... ADD (...)}。
     *
     * <p>使用 Oracle 语法，每条 ALTER 只加一列；不能完整还原的列只输出跳过提示。</p>
     *
     * @param schema  原始 schema 名；空串表示不限定 schema
     * @param table   原始表名
     * @param columns 选中的列
     * @return ALTER 语句及跳过提示；无列时返回空串
     */
    public static @NotNull String addColumns(@NotNull String schema, @NotNull String table,
                                             @NotNull List<ColumnInfo> columns) {
        String qualifiedTable = schema.isEmpty() ? quoteIdentifier(table)
                : quoteIdentifier(schema) + "." + quoteIdentifier(table);
        StringBuilder ddl = new StringBuilder();
        for (ColumnInfo column : columns) {
            String displayName = column.name().replace('\r', ' ').replace('\n', ' ');
            if (column.autoGenerated() || column.computed()) {
                // shortcut: DTO 缺少生成表达式和 identity 配置，补齐这些信息后再支持特殊列。
                appendLine(ddl, "-- 跳过 " + displayName + "：自增列或计算列缺少完整定义，请使用原生 DDL");
                continue;
            }
            if (column.typeDisplay().isEmpty()) {
                // 类型没读到（模型未加载 / 无权限）时拼出来的语句不可执行，留注释让人补，而不是生成错 SQL
                appendLine(ddl, "-- 跳过 " + displayName + "：未读到类型，请手工补全");
                continue;
            }
            appendLine(ddl, "ALTER TABLE " + qualifiedTable
                    + " ADD (" + columnDefinition(column) + ");");
            // shortcut: 只输出 Oracle 风格的 COMMENT ON COLUMN；MySQL 要 MODIFY COLUMN ... COMMENT。
            // 本插件目标库是 Oracle（见 README），等出现非 Oracle 目标时再按 Dbms 分支。
            if (!column.comment().isEmpty()) {
                appendLine(ddl, "COMMENT ON COLUMN " + qualifiedTable + "." + quoteIdentifier(column.name())
                        + " IS '" + escapeLiteral(column.comment()) + "';");
            }
        }
        return ddl.toString();
    }

    private static void appendLine(@NotNull StringBuilder ddl, @NotNull String line) {
        if (ddl.length() > 0) {
            ddl.append('\n');
        }
        ddl.append(line);
    }

    /** 单列定义：{@code NAME TYPE [DEFAULT x] [NOT NULL]}。 */
    static @NotNull String columnDefinition(@NotNull ColumnInfo column) {
        StringBuilder definition = new StringBuilder(quoteIdentifier(column.name())).append(' ').append(column.typeDisplay());
        if (!column.defaultValue().isEmpty()) {
            definition.append(" DEFAULT ").append(column.defaultValue());
        }
        if (column.notNull()) {
            definition.append(" NOT NULL");
        }
        return definition.toString();
    }

    /** SQL 字符串字面量里的单引号要写成两个。 */
    private static @NotNull String escapeLiteral(@NotNull String value) {
        return value.replace("'", "''");
    }

    private static @NotNull String quoteIdentifier(@NotNull String name) {
        return "\"" + name.replace("\"", "\"\"") + "\"";
    }
}
