package com.example.tablestructure.model;

import org.jetbrains.annotations.NotNull;

/**
 * 列信息。
 *
 * @param position    列序号（Oracle 中即 COLUMN_ID）
 * @param typeDisplay 完整类型展示，如 {@code VARCHAR2(50 CHAR)} / {@code NUMBER(10,2)}
 * @param length      长度（字符/字节/数字长度，0 表示不适用）
 * @param precision   精度（0 表示不适用）
 * @param scale       标度（0 表示不适用）
 */
public record ColumnInfo(
        int position,
        @NotNull String name,
        @NotNull String typeDisplay,
        int length,
        int precision,
        int scale,
        boolean notNull,
        @NotNull String defaultValue,
        boolean primaryKey,
        boolean foreignKey,
        boolean autoGenerated,
        boolean computed,
        @NotNull String comment
) {
}
